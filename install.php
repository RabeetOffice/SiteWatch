$detectedUrl = $s['app']['url'] ?? $baseUrl;
$cronPath = str_replace('\\', '/', $root) . '/cron/monitor.php';
$steps = ['Requirements', 'Database', 'Tables', 'Admin', 'Settings', 'Complete'];
