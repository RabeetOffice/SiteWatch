<?php

declare(strict_types=1);

/**
 * SiteWatch installation wizard.
 *
 * Steps: 1 Requirements → 2 Database → 3 Tables → 4 Admin account → 5 Application settings → 6 Complete
 * Creates storage/install.lock when finished. Delete that file to run the installer again.
 */

define('SW_INSTALLER', true);
require __DIR__ . '/bootstrap.php';

use App\Core\App;
use App\Core\Crypto;
use App\Core\Database;
use App\Core\Request;
use App\Core\Response;
use App\Core\Validator;
use App\Repositories\SettingsRepository;
use App\Repositories\UserRepository;

$root = __DIR__;
$lockFile = $root . '/storage/install.lock';
$session = App::session();
$csrf = App::csrf();
$nonce = defined('SW_CSP_NONCE') ? SW_CSP_NONCE : '';
$baseUrl = App::detectBaseUrl();

$state = $session->get('_install', []);
if (!is_array($state)) {
    $state = [];
}
$step = max(1, min(6, (int) ($_GET['step'] ?? $state['step'] ?? 1)));
$errors = [];
$notice = null;

$installed = is_file($lockFile);
$maxReached = (int) ($state['step'] ?? 1);
if (!$installed && $step > $maxReached) {
    $step = $maxReached;
}

// ---------------------------------------------------------------------------
// Requirement checks
// ---------------------------------------------------------------------------
$requirements = [];
$requirements[] = ['PHP 8.2 or newer', PHP_VERSION, version_compare(PHP_VERSION, '8.2.0', '>=') ? 'ok' : 'bad'];
foreach (['pdo' => 'PDO', 'pdo_mysql' => 'PDO MySQL', 'curl' => 'cURL', 'openssl' => 'OpenSSL', 'json' => 'JSON', 'mbstring' => 'mbstring'] as $ext => $label) {
    $requirements[] = [$label . ' extension', extension_loaded($ext) ? 'loaded' : 'missing', extension_loaded($ext) ? 'ok' : 'bad'];
}
$requirements[] = ['intl extension (optional, for international domains)', extension_loaded('intl') ? 'loaded' : 'missing', extension_loaded('intl') ? 'ok' : 'warn'];
$requirements[] = ['Composer dependencies (vendor/)', is_file($root . '/vendor/autoload.php') ? 'installed' : 'missing — run composer install', is_file($root . '/vendor/autoload.php') ? 'ok' : 'bad'];
foreach (['storage', 'storage/logs', 'storage/cache', 'storage/locks'] as $dir) {
    $path = $root . '/' . $dir;
    if (!is_dir($path)) {
        @mkdir($path, 0755, true);
    }
    $requirements[] = [$dir . '/ writable', is_writable($path) ? 'writable' : 'not writable', is_writable($path) ? 'ok' : 'bad'];
}
$envWritable = is_file($root . '/.env') ? is_writable($root . '/.env') : is_writable($root);
$requirements[] = ['.env writable', $envWritable ? 'yes' : 'no — create .env manually from .env.example', $envWritable ? 'ok' : 'warn'];
$requirements[] = ['allow_url_fopen / cURL SSL', (curl_version()['ssl_version'] ?? '') !== '' ? curl_version()['ssl_version'] : 'no SSL support in cURL', (curl_version()['ssl_version'] ?? '') !== '' ? 'ok' : 'bad'];
$requirementsOk = !in_array('bad', array_column($requirements, 2), true);

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------
$dbConfig = static function (array $s): array {
    return [
        'host'     => (string) ($s['db']['host'] ?? '127.0.0.1'),
        'port'     => (int) ($s['db']['port'] ?? 3306),
        'name'     => (string) ($s['db']['name'] ?? 'sitewatch'),
        'user'     => (string) ($s['db']['user'] ?? ''),
        'password' => (string) ($s['db']['password'] ?? ''),
        'charset'  => 'utf8mb4',
        'options'  => [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION, PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC, PDO::ATTR_EMULATE_PREPARES => false],
    ];
};

$envValue = static function (string $value): string {
    if ($value === '' || preg_match('/^[A-Za-z0-9_\-.:\/+=@]+$/', $value)) {
        return $value;
    }
    return '"' . str_replace(['\\', '"'], ['\\\\', '\\"'], $value) . '"';
};

$writeEnv = static function (array $s, string $appKey) use ($root, $envValue): void {
    $lines = [
        '# SiteWatch environment configuration — generated by install.php on ' . gmdate('Y-m-d H:i:s') . ' UTC',
        'APP_ENV=production',
        'APP_DEBUG=false',
        'APP_URL=' . $envValue((string) ($s['app']['url'] ?? '')),
        'APP_TIMEZONE=' . $envValue((string) ($s['app']['timezone'] ?? 'Asia/Karachi')),
        'APP_KEY=' . $envValue($appKey),
        '',
        'DB_HOST=' . $envValue((string) $s['db']['host']),
        'DB_PORT=' . $envValue((string) $s['db']['port']),
        'DB_NAME=' . $envValue((string) $s['db']['name']),
        'DB_USER=' . $envValue((string) $s['db']['user']),
        'DB_PASSWORD=' . $envValue((string) $s['db']['password']),
        '',
        'SESSION_LIFETIME=480',
        'LOGIN_MAX_ATTEMPTS=5',
        'LOGIN_LOCKOUT_MINUTES=15',
        'LOG_LEVEL=info',
        'LOG_MAX_FILES=14',
        '',
        '# SSRF protection: keep false unless you intentionally monitor private/internal websites',
        'MONITOR_ALLOW_PRIVATE=false',
        'MONITOR_MAX_PER_RUN=300',
        '',
    ];
    if (is_file($root . '/.env')) {
        @copy($root . '/.env', $root . '/.env.backup-' . gmdate('YmdHis'));
    }
    if (file_put_contents($root . '/.env', implode("\n", $lines)) === false) {
        throw new RuntimeException('Unable to write the .env file. Check directory permissions.');
    }
};

// ---------------------------------------------------------------------------
// Handle POST
// ---------------------------------------------------------------------------
if (Request::isPost() && !$installed) {
    if (!$csrf->validateRequest()) {
        $errors['_'] = 'Your session expired. Please try again.';
    } else {
        $action = (string) ($_POST['action'] ?? '');
        try {
            if ($action === 'requirements') {
                if (!$requirementsOk) {
                    $errors['_'] = 'Please resolve the failed requirements before continuing.';
                } else {
                    $state['step'] = 2;
                    $step = 2;
                }
            } elseif ($action === 'database') {
                $v = new Validator($_POST);
                $v->required('db_host', 'Host')->required('db_name', 'Database name')->required('db_user', 'Username')->integer('db_port', 1, 65535, 'Port');
                $v->regex('db_name', '/^[A-Za-z0-9_\-]+$/', 'Database name may only contain letters, numbers, - and _.');
                if ($v->fails()) {
                    $errors = $v->errors();
                } else {
                    $state['db'] = [
                        'host'     => trim((string) $_POST['db_host']),
                        'port'     => (int) ($_POST['db_port'] ?: 3306),
                        'name'     => trim((string) $_POST['db_name']),
                        'user'     => trim((string) $_POST['db_user']),
                        'password' => (string) ($_POST['db_password'] ?? ''),
                    ];
                    $config = $dbConfig($state);
                    $create = !empty($_POST['db_create']);
                    try {
                        $pdo = Database::connect($config, true);
                    } catch (Throwable $e) {
                        if ($create && (str_contains($e->getMessage(), 'Unknown database') || str_contains($e->getMessage(), '1049'))) {
                            $server = Database::connect($config, false);
                            $server->exec('CREATE DATABASE `' . str_replace('`', '', $config['name']) . '` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci');
                            $pdo = Database::connect($config, true);
                        } else {
                            throw $e;
                        }
                    }
                    $version = (string) $pdo->getAttribute(PDO::ATTR_SERVER_VERSION);
                    $state['db_version'] = $version;
                    $state['step'] = 3;
                    $step = 3;
                    $notice = 'Connected to MySQL/MariaDB ' . $version . '.';
                }
            } elseif ($action === 'tables') {
                $config = $dbConfig($state);
                $pdo = Database::connect($config, true);
                $sql = (string) file_get_contents($root . '/database/schema.sql');
                if ($sql === '') {
                    throw new RuntimeException('database/schema.sql is missing.');
                }
                $pdo->exec($sql);
                $tables = $pdo->query('SHOW TABLES')->fetchAll(PDO::FETCH_COLUMN);
                $state['tables'] = count($tables);
                $state['step'] = 4;
                $step = 4;
                $notice = count($tables) . ' tables are ready.';
            } elseif ($action === 'admin') {
                $v = new Validator($_POST);
                $v->required('admin_name', 'Name')->max('admin_name', 100, 'Name');
                $v->required('admin_email', 'Email')->email('admin_email', 'Email');
                $v->required('admin_password', 'Password')->min('admin_password', 10, 'Password');
                if (($_POST['admin_password'] ?? '') !== ($_POST['admin_password_confirmation'] ?? '')) {
                    $v->addError('admin_password_confirmation', 'The password confirmation does not match.');
                }
                if ($v->fails()) {
                    $errors = $v->errors();
                } else {
                    $state['admin'] = ['name' => trim((string) $_POST['admin_name']), 'email' => mb_strtolower(trim((string) $_POST['admin_email'])), 'password' => (string) $_POST['admin_password']];
                    $state['step'] = 5;
                    $step = 5;
                }
            } elseif ($action === 'settings') {
                $v = new Validator($_POST);
                $v->required('app_name', 'Application name')->max('app_name', 100, 'Application name');
                $v->required('app_url', 'Application URL')->url('app_url', 'Application URL');
                $v->required('app_timezone', 'Timezone')->timezone('app_timezone', 'Timezone');
                $v->in('default_check_interval', [1, 2, 5, 10, 15, 30], 'Default interval');
                if ($v->fails()) {
                    $errors = $v->errors();
                } else {
                    $state['app'] = [
                        'name'     => trim((string) $_POST['app_name']),
                        'url'      => rtrim(trim((string) $_POST['app_url']), '/'),
                        'timezone' => (string) $_POST['app_timezone'],
                        'interval' => (int) ($_POST['default_check_interval'] ?? 5),
                    ];

                    // ---- Finish installation ----
                    $config = $dbConfig($state);
                    $db = new Database($config);
                    $appKey = Crypto::generateKey();
                    $writeEnv($state, $appKey);

                    $users = new UserRepository($db);
                    $existing = $users->findByEmail($state['admin']['email']);
                    if ($existing === null) {
                        $users->create($state['admin']['name'], $state['admin']['email'], $state['admin']['password']);
                    } else {
                        $users->updatePassword((int) $existing['id'], $state['admin']['password']);
                        $users->updateProfile((int) $existing['id'], $state['admin']['name'], $state['admin']['email']);
                    }

                    $settings = new SettingsRepository($db);
                    $settings->setMany([
                        'app_name'               => $state['app']['name'],
                        'app_url'                => $state['app']['url'],
                        'app_timezone'           => $state['app']['timezone'],
                        'default_check_interval' => $state['app']['interval'],
                    ]);

                    $db->insert('activity_logs', [
                        'action'      => 'settings.changed',
                        'description' => 'SiteWatch installed',
                        'created_at'  => gmdate('Y-m-d H:i:s'),
                    ]);

                    file_put_contents($lockFile, "installed " . gmdate('Y-m-d H:i:s') . " UTC\n");
                    $state['step'] = 6;
                    $step = 6;
                    $installed = true;
                    unset($state['admin']['password'], $state['db']['password']);
                }
            } elseif ($action === 'back') {
                $target = max(1, (int) ($_POST['target'] ?? 1));
                $state['step'] = min($target, (int) ($state['step'] ?? 1));
                $step = $target;
            }
        } catch (Throwable $e) {
            $errors['_'] = $e->getMessage();
        }
    }
    $session->set('_install', $state);
}

