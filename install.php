                        <div class="col-md-4"><label class="form-label">Port</label><input type="number" class="form-control<?= isset($errors['db_port']) ? ' is-invalid' : '' ?>" name="db_port" value="<?= e((string) ($s['db']['port'] ?? 3306)) ?>"><div class="invalid-feedback"><?= e($errors['db_port'] ?? '') ?></div></div>
                        <div class="col-md-12"><label class="form-label">Database name</label><input type="text" class="form-control<?= isset($errors['db_name']) ? ' is-invalid' : '' ?>" name="db_name" value="<?= e($s['db']['name'] ?? 'sitewatch') ?>"><div class="invalid-feedback"><?= e($errors['db_name'] ?? '') ?></div></div>
                        <div class="col-md-6"><label class="form-label">Username</label><input type="text" class="form-control<?= isset($errors['db_user']) ? ' is-invalid' : '' ?>" name="db_user" value="<?= e($s['db']['user'] ?? 'root') ?>" autocomplete="off"><div class="invalid-feedback"><?= e($errors['db_user'] ?? '') ?></div></div>
